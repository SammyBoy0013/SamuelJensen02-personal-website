// Turns the outlined brand SVGs in public/brand into inline markup, so the
// seal and monogram can take their colour from CSS (currentColor).
// Run with `npm run brand` after changing a file in public/brand.
import { readFileSync, writeFileSync } from "node:fs";

const read = (name) => readFileSync(`public/brand/${name}.svg`, "utf8");

const inner = (svg) =>
  svg
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .replace(/<title>[\s\S]*?<\/title>/, "")
    .trim();

// Mark the two seal rings so the loader can draw them with stroke-dashoffset.
const seal = inner(read("seal")).replace(
  /<circle cx="300.0" cy="300.0" r="(291.00|207.00)"/g,
  '<circle class="seal-ring" pathLength="1" cx="300.0" cy="300.0" r="$1"',
);
const monogram = inner(read("monogram"));

writeFileSync(
  "components/brand/markup.ts",
  `// Generated by scripts/generate-brand.mjs from public/brand. Do not edit by hand.\n\n` +
    `export const sealMarkup = ${JSON.stringify(seal)};\n\n` +
    `export const monogramMarkup = ${JSON.stringify(monogram)};\n`,
);
console.log("Wrote components/brand/markup.ts");
